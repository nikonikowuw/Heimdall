-- 整体下发配置的乐观并发保护：任务级配置版本号
--
-- 算法实例的写路径已收敛为「整份任务配置一次下发」，该请求是整体覆盖语义：
-- 客户端携带打开编辑器时的快照版本号，服务端不匹配即拒绝，避免两个会话
-- 各自基于旧快照保存、互相覆盖对方刚写入的实例集合与参数。
--
-- 1) config_revision：任务配置版本号，配置写入一律 +1（整体下发是覆盖写，
--    重复提交同一份内容同样推进，客户端每次都用响应里的新版本号刷新本地快照）；
--    运行时状态回写（actual_status / status_message / applied_revision）不改变它，
--    否则每次状态刷新都会让在途保存失效。
-- 2) 存量行一律 0：迁移前不存在版本概念，首个携带版本号的客户端会先读到当前值。
ALTER TABLE analysis_tasks ADD COLUMN config_revision INTEGER NOT NULL DEFAULT 0;
